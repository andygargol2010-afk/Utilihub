#!/usr/bin/env node
/**
 * Lists every EN/ES tool page served with noindex by the content-quality rule
 * (src/lib/content-quality.ts, MIN_OWN_GUIDE_WORDS) and writes docs/noindex-tools.md.
 *
 *   node scripts/list-noindex-tools.mjs            # writes docs/noindex-tools.md
 *   node scripts/list-noindex-tools.mjs --stdout   # prints only the counts
 *
 * Uses the same inputs as the sitemap/route loaders (ALL_TOOLS, toolSeoGuideData, financeSeo),
 * loaded through vite's SSR module loader so the "@/" alias and TS work.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { createServer } from "vite";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("../src", import.meta.url));

const server = await createServer({
  configFile: false,
  resolve: { alias: { "@": src } },
  server: { middlewareMode: true, hmr: false, watch: null },
  appType: "custom",
  logLevel: "error",
});
try {
  const load = (p) => server.ssrLoadModule(p);
  const { ALL_TOOLS, toolHref } = await load("/src/lib/all-tools.ts");
  const { toolSeoGuideData } = await load("/src/lib/tool-seo-overrides.ts");
  const { financeSeo } = await load("/src/lib/finance-seo-content.ts");
  const { usesFinanceRoute, toolByEnglishSlug, spanishToolPath } = await load("/src/lib/route-slugs.ts");
  const { isIndexableTool, isIndexableFinance, ownGuideWords, MIN_OWN_GUIDE_WORDS } = await load("/src/lib/content-quality.ts");
  const { isRedirectedToolSlug } = await load("/src/lib/canonical-tool-redirects.ts");

  const rows = [];
  for (const tool of ALL_TOOLS) {
    if (isRedirectedToolSlug(tool.slug)) continue;
    const enPath = toolHref(tool);
    const finance = usesFinanceRoute(tool);
    const owns = finance || toolByEnglishSlug(ALL_TOOLS, enPath.split("/").pop() ?? "")?.slug === tool.slug;
    const guide = finance ? null : toolSeoGuideData(tool);
    const idx = (l) => (guide ? isIndexableTool(tool, guide, l, ALL_TOOLS) : isIndexableFinance(financeSeo(tool.slug), l));
    const words = (l) => (guide ? ownGuideWords(tool, guide, l, ALL_TOOLS) : "-");
    const en = idx("en"), es = idx("es");
    if (owns && en && es) continue;
    if (!owns && es) continue;
    rows.push({ slug: tool.slug, category: tool.category ?? "", enPath: owns ? enPath : "(shared URL)", esPath: spanishToolPath(tool), en: owns ? en : null, es, wEn: words("en"), wEs: words("es") });
  }
  const noEn = rows.filter((r) => r.en === false).length;
  const noEs = rows.filter((r) => !r.es).length;
  const summary = `tools=${ALL_TOOLS.length} noindexEN=${noEn} noindexES=${noEs} (MIN_OWN_GUIDE_WORDS=${MIN_OWN_GUIDE_WORDS})`;
  console.log(`list-noindex-tools: ${summary}`);
  if (!process.argv.includes("--stdout")) {
    const byCat = {};
    for (const r of rows) (byCat[r.category] ??= []).push(r);
    const lines = [
      "# Tool pages served with noindex (content-quality rule)",
      "",
      "Generated by `node scripts/list-noindex-tools.mjs`. A page is noindex while it has fewer than",
      `${MIN_OWN_GUIDE_WORDS} words of its own guide text (src/lib/content-quality.ts). Regenerate after adding copy.`,
      "",
      `**Total:** ${summary}`,
      "",
      "| slug | category | EN path | EN | own words EN | ES path | ES | own words ES |",
      "|---|---|---|---|---|---|---|---|",
    ];
    const mark = (v) => (v === null ? "—" : v ? "index" : "noindex");
    for (const cat of Object.keys(byCat).sort())
      for (const r of byCat[cat].sort((a, b) => a.slug.localeCompare(b.slug)))
        lines.push(`| ${r.slug} | ${r.category} | ${r.enPath} | ${mark(r.en)} | ${r.wEn} | ${r.esPath} | ${mark(r.es)} | ${r.wEs} |`);
    mkdirSync("docs", { recursive: true });
    writeFileSync("docs/noindex-tools.md", lines.join("\n") + "\n");
    console.log(`list-noindex-tools: wrote docs/noindex-tools.md (${rows.length} rows)`);
  }
} finally {
  await server.close();
}
